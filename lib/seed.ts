/** تعبئة قاعدة بيانات فارغة ببيانات البداية. */
export function seedDatabase(conn: Database.Database): void {
  const insertCategory = conn.prepare(
    `INSERT INTO categories (name, slug, description, icon, sort_order)
     VALUES (@name, @slug, @description, @icon, @sort_order)`,
  );
  const insertFatwa = conn.prepare(
    `INSERT INTO fatwas (number, slug, title, question, answer, category_id, source, tags, published)
     VALUES (@number, @slug, @title, @question, @answer, @category_id, @source, @tags, 1)`,
  );
  const insertBook = conn.prepare(
    `INSERT INTO books (title, description, year, publisher, volumes, sort_order)
     VALUES (@title, @description, @year, @publisher, @volumes, @sort_order)`,
  );
  const insertSetting = conn.prepare(
    `INSERT INTO settings (key, value) VALUES (?, ?)
     ON CONFLICT(key) DO NOTHING`,
  );

  conn.transaction(() => {
    const categoryIds = new Map<string, number>();
    CATEGORIES.forEach((category, i) => {
      const result = insertCategory.run({ ...category, sort_order: i });
      categoryIds.set(category.slug, Number(result.lastInsertRowid));
    });

    for (const fatwa of FATWAS) {
      const result = insertFatwa.run({
        number: fatwa.number,
        slug: fatwa.slug,
        title: fatwa.title,
        question: fatwa.question,
        answer: fatwa.answer,
        category_id: categoryIds.get(fatwa.category) ?? null,
        source: DEMO_SOURCE,
        tags: fatwa.tags,
      });
      indexFatwa(conn, { ...fatwa, id: Number(result.lastInsertRowid) });
    }

    BOOKS.forEach((book, i) => insertBook.run({ ...book, sort_order: i }));
    for (const [key, value] of Object.entries(SETTINGS)) insertSetting.run(key, value);
  })();
}
